#!/usr/bin/env python3
"""Derive the confidence->precision map that gates paid classification.

Run against the development sets only. Writes config/calibration.yaml, which
the router loads at startup. Bands that fall below the policy's precision floor
-- or that have too few observations to judge -- are marked `commit: false`, so
the fabric escalates to the LLM classifier there.

    python eval/calibrate.py
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from decision_fabric import features as F  # noqa: E402
from decision_fabric.seed import Fabric  # noqa: E402

BANDS = [(0.0, 0.35), (0.35, 0.5), (0.5, 0.6), (0.6, 0.7), (0.7, 0.8), (0.8, 0.9), (0.9, 1.01)]


def main() -> int:
    fab = Fabric()
    cls_cfg = fab.policies_cfg["classification"]
    floor = float(cls_cfg["min_commit_precision"])
    min_support = int(cls_cfg["min_band_support"])

    rows = []
    for name in ("dev.jsonl", "dev2.jsonl"):
        p = pathlib.Path(__file__).parent / name
        if p.is_file():
            rows += [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
    print(f"calibrating on {len(rows)} development queries\n")

    scored = []
    for r in rows:
        f = F.extract(r["q"], fab.signals, scope_cfg=fab.scope_signals)
        scored.append((r["label"], f.task_type, f.task_confidence))

    lines = [
        "# GENERATED by eval/calibrate.py -- do not hand-edit.",
        "# Maps heuristic confidence bands to their MEASURED precision on the",
        "# development sets. `commit: true` means the fabric may trust the",
        "# heuristic in that band and skip the paid LLM classification.",
        f"# floor: {floor}  min_support: {min_support}  n: {len(rows)}",
        "bands:",
    ]
    print(f"  {'band':<16}{'n':>5}{'precision':>11}{'commit':>9}")
    committed = 0
    for lo, hi in BANDS:
        band = [s for s in scored if lo <= s[2] < hi]
        n = len(band)
        if n == 0:
            prec, commit = None, False
        else:
            prec = sum(1 for e, g, _ in band if e == g) / n
            commit = bool(n >= min_support and prec >= floor)
        committed += n if commit else 0
        shown = f"{prec:.3f}" if prec is not None else "  n/a"
        print(f"  [{lo:.2f},{hi:.2f})   {n:>5}{shown:>11}{str(commit):>9}")
        lines.append(f"  - {{lo: {lo}, hi: {hi}, n: {n}, "
                     f"precision: {round(prec, 4) if prec is not None else 'null'}, "
                     f"commit: {str(commit).lower()}}}")

    out = ROOT / "config" / "calibration.yaml"
    out.write_text("\n".join(lines) + "\n")
    print(f"\ncommit rate at this floor: {committed}/{len(rows)} = "
          f"{100*committed/len(rows):.0f}% of queries skip the LLM call")
    print(f"written: {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
